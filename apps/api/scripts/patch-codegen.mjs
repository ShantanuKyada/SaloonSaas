// kysely-codegen types int8 as string; the pg pool parses int8 to number (money/counts fit in 2^53).
import { readFileSync, writeFileSync } from 'node:fs';

const file = new URL('../src/db/schema.generated.ts', import.meta.url);
let source = readFileSync(file, 'utf8');
source = source.replace(
  /export type Int8 = ColumnType<string, bigint \| number \| string, bigint \| number \| string>;/,
  'export type Int8 = ColumnType<number, bigint | number | string, bigint | number | string>;',
);
source = source.replace(
  /export type Numeric = ColumnType<string, number \| string, number \| string>;/,
  'export type Numeric = ColumnType<number, number | string, number | string>;',
);
writeFileSync(file, `/* eslint-disable */\n// Generated by kysely-codegen from the live schema — run \`npm run db:codegen\` after migrations.\n${source.replace(/^\/\*\*[\s\S]*?\*\/\n/, '')}`);
console.log('Patched schema.generated.ts');
